#include <iostream>
#include <clocale>

using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    double avg;
    int attendance, debts;

    cout << "Введите средний балл 0..10: ";
    cin >> avg;
    cout << "Введите посещаемость 0..100: ";
    cin >> attendance;
    cout << "Введите количество задолженностей: ";
    cin >> debts;

    if (avg < 0 || avg > 10 || attendance < 0 || attendance > 100 || debts < 0) {
        cout << "Ошибка: данные вне допустимых диапазонов.\n";
        return 0;
    }

    int rule = 0;

    if (debts == 0) {
        if (avg >= 9.5 && attendance >= 70) {
            rule = 2;
        }
        else if (avg >= 8.0 && attendance >= 80) {
            rule = 1;
        }
    }

    switch (rule) {
    case 1:
        cout << "Решение: можно выбрать углублённый курс.\n";
        cout << "Сработало правило: средний балл >= 8, посещаемость >= 80, задолженностей нет.\n";
        break;
    case 2:
        cout << "Решение: можно выбрать углублённый курс.\n";
        cout << "Сработало правило: средний балл >= 9.5, посещаемость >= 70, задолженностей нет.\n";
        break;
    default:
        cout << "Решение: нельзя выбрать углублённый курс.\n";
        cout << "Причина: ";
        if (debts != 0) {
            cout << "есть задолженности";
        }
        else if (avg >= 9.5) {
            if (attendance < 70)
                cout << "посещаемость ниже 70 при среднем балле >= 9.5";
            else
                cout << "условия не выполнены";
        }
        else if (avg >= 8.0) {
            if (attendance < 80)
                cout << "посещаемость ниже 80";
            else
                cout << "условия не выполнены";
        }
        else {
            cout << "средний балл ниже 8";
            if (attendance < 80)
                cout << " и посещаемость ниже 80";
        }
        cout << ".\n";
    }

    return 0;
}

